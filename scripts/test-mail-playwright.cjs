// Check the ENO hierarchy, migration, editing, Outlook imports, and responsive layout.
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { baseUrl, launchPlaywright } = require('./browser.cjs');
const MsgReader = require('@kenjiuno/msgreader').default;
(async () => {
 const browser = await launchPlaywright();
 try {
  const page = await browser.newPage({viewport:{width:1400,height:900}});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(() => { if (!localStorage.getItem('migration-tested')) { localStorage.setItem('frontdoor:mail-added',JSON.stringify([{id:'old-demo',title:'Old demo',preview:{to:'',subject:'Old',body:'Old'}}])); localStorage.setItem('frontdoor:mail-edits',JSON.stringify({'section-01-1':{title:'Old edited demo'}})); localStorage.setItem('migration-tested','true'); } });
  await page.goto(baseUrl+'#mail');
  await page.locator('.mail-section-row').first().waitFor();
  assert.equal(await page.locator('.mail-section-row').count(),46);
  assert.equal(await page.locator('.mail-subsection-row').count(),113);
  assert.equal(await page.locator('.mail-section-row:visible').count(),42);
  assert.equal(await page.locator('.mail-subsection-row:visible').count(),0);
  assert.equal(await page.locator('.mail-section-row').first().innerText(),'AI Usage');
  assert.deepEqual(await page.evaluate(()=>JSON.parse(localStorage.getItem('frontdoor:mail-added'))),[]);
  assert.deepEqual(await page.evaluate(()=>JSON.parse(localStorage.getItem('frontdoor:mail-edits'))),{});
  await page.getByRole('button',{name:'AI Usage',exact:true}).click();
  assert.equal(await page.locator('.mail-subsection-row:visible').count(),3);
  await page.getByRole('button',{name:'AI Usage',exact:true}).click();
  assert.equal(await page.locator('.mail-subsection-row:visible').count(),0);
  const search=page.getByRole('searchbox',{name:'Search portal'});
  await search.fill('SIR Request Template.oft');
  await page.waitForFunction(()=>document.querySelectorAll('.mail-subsection-row').length===3);
  assert.equal(await page.locator('.mail-subsection-row:visible').count(),3);
  const ids=await page.locator('.mail-subsection-row').evaluateAll(rows=>rows.map(r=>r.dataset.mailPreviewToggle)); assert.equal(new Set(ids).size,3);
  await search.fill('SEN Emails');
  await page.getByRole('button',{name:'Old SEN emails',exact:true}).waitFor();
  const order=await page.locator('.mail-section-row,.mail-subsection-row').evaluateAll(rows=>rows.map(r=>r.innerText));
  assert.ok(order.findIndex(t=>t.includes('Old SEN emails'))<order.findIndex(t=>t.includes('HQ NOSC assistance request.oft')));
  await search.fill('Approved - Downloaded AI Tool.oft');await page.waitForFunction(()=>document.querySelectorAll('.mail-subsection-row').length===1);
  const sampleEvent = page.waitForEvent('download');
  await page.locator('[data-mail-download]:visible').click();
  const sampleDownload = await sampleEvent;
  assert.equal(sampleDownload.suggestedFilename(),'Approved - Downloaded AI Tool.oft');
  const sampleData = new MsgReader(await fs.readFile(await sampleDownload.path())).getFileData();
  assert.match(sampleData.subject,/^\[EXAMPLE\]/);
  assert.match(sampleData.body,/EXAMPLE TEMPLATE/);
  const row=page.locator('.mail-subsection-row:visible').first(); await row.press('Enter');
  const form=page.locator('.mail-preview:visible');
  assert.match(await form.getByLabel('Body',{exact:true}).inputValue(),/EXAMPLE TEMPLATE/);
  await form.getByLabel('To',{exact:true}).fill('review@example.com');
  await form.getByLabel('Subject',{exact:true}).fill('Reviewed template');
  await form.getByLabel('Body',{exact:true}).fill('Approved content for local review.');
  await form.getByRole('button',{name:'Save',exact:true}).click(); await row.press('Enter');
  const event=page.waitForEvent('download'); await row.locator('[data-mail-download]').click();const download=await event;
  assert.equal(download.suggestedFilename(),'Approved - Downloaded AI Tool.oft');
  const bytes=await fs.readFile(await download.path());const data=new MsgReader(bytes).getFileData(); assert.equal(data.subject,'Reviewed template');assert.match(data.body,/Approved content/);
  await page.reload();await search.fill('Approved - Downloaded AI Tool.oft');await page.waitForFunction(()=>document.querySelectorAll('.mail-subsection-row').length===1);await row.press('Enter');
  assert.equal(await form.getByLabel('Subject',{exact:true}).inputValue(),'Reviewed template');
  await form.locator('[data-mail-upload]').setInputFiles({name:'invalid.oft',mimeType:'application/octet-stream',buffer:Buffer.from('invalid')});await form.getByText(/Import failed/).waitFor();
  await form.locator('[data-mail-upload]').setInputFiles({name:'review.oft',mimeType:'application/octet-stream',buffer:bytes});await form.getByText(/Imported review.oft/).waitFor();
  await search.fill('');
  await page.getByRole('button',{name:'Add Email',exact:true}).click();const dialog=page.locator('#mail-add-dialog');await dialog.getByRole('button',{name:'Cancel',exact:true}).click();assert.equal(await page.locator('.mail-subsection-row').count(),113);
  await page.getByRole('button',{name:'Add Email',exact:true}).click();await dialog.locator('[name=title]').fill('Added review email');await dialog.locator('[name=subject]').fill('Added subject');await dialog.locator('[name=body]').fill('Added body');await dialog.getByRole('button',{name:'Save',exact:true}).click();
  assert.equal(await page.locator('.mail-subsection-row:visible').count(),4);
  await page.reload();await search.fill('Added review email');await page.waitForFunction(()=>document.querySelectorAll('.mail-subsection-row').length===1);await page.locator('.mail-subsection-row:visible').waitFor();await page.locator('[data-mail-delete]:visible').click();await page.getByText('No mail templates match.',{exact:true}).waitFor();
  await search.fill('');await page.locator('#mail-section-select').selectOption('');
  await page.setViewportSize({width:390,height:844});await search.fill('Unauthorized Software');await page.getByRole('button',{name:'Unauthorized Software',exact:true}).waitFor();
  assert.equal(await page.locator('.table-wrap').evaluate(el=>el.scrollWidth<=el.clientWidth+1),true);
  assert.deepEqual(errors,[]);
  await page.screenshot({path:path.join(__dirname,'../../frontdoor-mail-preview.png'),fullPage:true});
  console.log('Mail hierarchy, migration, editing, import, download, persistence, and mobile checks passed.');
 } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
