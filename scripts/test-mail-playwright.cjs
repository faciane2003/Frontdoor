// Check Mail editing, persistence, imports, generated Outlook files, and responsive behavior.
const assert = require("node:assert/strict");
const { baseUrl, launchPlaywright } = require("./browser.cjs");
const fs = require("node:fs/promises");
const path = require("node:path");
const MsgReader = require("@kenjiuno/msgreader").default;

(async () => {
  const browser = await launchPlaywright();
  try {
    const page = await browser.newPage({ viewport: { width: 1400, height: 900 } });
    const errors = [];
    page.on("pageerror", (error) => errors.push(error.message));
    await page.goto(baseUrl);
    await page.getByRole("button", { name: "Mail", exact: true }).click();
    await page.locator(".mail-section-row").first().waitFor();
    assert.equal(await page.locator(".mail-section-row").count(), 5);
    assert.equal(await page.locator(".mail-subsection-row").count(), 30);
    assert.equal(await page.locator(".mail-subsection-row:visible").count(), 0);
    assert.equal(await page.locator(".mail-table thead").isVisible(), false);
    assert.equal(await page.locator("[data-mail-toggle][aria-expanded='false']").count(), 5);
    assert.equal(await page.locator(".mail-table a[download]").count(), 30);
    assert.equal(await page.locator(".mail-table").evaluate((table) => table.classList.contains("resource-table")), true);
    const appearance = (button) => {
      const style = getComputedStyle(button);
      return [style.backgroundColor, style.color, style.padding, style.minHeight, style.fontSize, style.cursor];
    };
    const mailToggle = page.locator("[data-mail-toggle]").first();
    await mailToggle.hover();
    const mailHover = await mailToggle.evaluate(appearance);
    await page.getByRole("button", { name: "Links", exact: true }).click();
    const linksToggle = page.locator("[data-link-category-toggle]").first();
    await linksToggle.hover();
    assert.deepEqual(await linksToggle.evaluate(appearance), mailHover);
    await page.getByRole("button", { name: "Mail", exact: true }).click();
    await page.locator("#mail-section-select").selectOption("section-04");
    assert.equal(await page.locator(".mail-section-row").count(), 1);
    assert.equal(await page.locator(".mail-subsection-row").count(), 6);
    await page.locator("#mail-section-select").selectOption("");
    await page.getByRole("button", { name: /Incident Response/ }).click();
    assert.equal(await page.getByRole("link", { name: "Initial Notification", exact: true }).isVisible(), true);
    assert.equal(await page.locator(".mail-table thead").isVisible(), true);
    await page.getByRole("button", { name: /Incident Response/ }).click();
    assert.equal(await page.getByRole("link", { name: "Initial Notification", exact: true }).isVisible(), false);
    await page.getByRole("button", { name: /Incident Response/ }).click();
    assert.equal(await page.getByRole("link", { name: "Initial Notification", exact: true }).isVisible(), true);
    const downloadEvent = page.waitForEvent("download");
    await page.getByRole("link", { name: "Initial Notification", exact: true }).click();
    const download = await downloadEvent;
    assert.equal(download.suggestedFilename(), "section-01-1.oft");
    assert.equal(await download.failure(), null);
    const preview = page.locator("#mail-preview-section-01-1");
    const emailRow = page.locator('[data-mail-preview-toggle="section-01-1"]');
    assert.equal(await preview.isVisible(), false);
    await emailRow.locator("td").first().click({ position: { x: 5, y: 5 } });
    assert.equal(await preview.isVisible(), true);
    assert.match(await preview.getByLabel("Subject", { exact: true }).inputValue(), /\[DUMMY TEMPLATE\] Initial Notification/);
    assert.match(await preview.getByLabel("Body", { exact: true }).inputValue(), /Hello \[Recipient\]/);
    await preview.getByLabel("To", { exact: true }).fill("updated@example.com");
    await preview.getByLabel("Subject", { exact: true }).fill("Updated incident template");
    await preview.getByLabel("Body", { exact: true }).fill("Hello team,\n\nUpdated incident details for this saved template.");
    await preview.getByRole("button", { name: "Save", exact: true }).click();
    await preview.getByText("Saved. Title downloads now use this email.", { exact: true }).waitFor();
    await emailRow.press("Enter");
    const updatedDownloadEvent = page.waitForEvent("download");
    await page.getByRole("link", { name: "Initial Notification", exact: true }).click();
    const updatedDownload = await updatedDownloadEvent;
    const updatedData = new MsgReader(await fs.readFile(await updatedDownload.path())).getFileData();
    assert.equal(updatedData.subject, "Updated incident template");
    assert.match(updatedData.body, /Updated incident details/);
    assert.equal(updatedData.recipients[0].email, "updated@example.com");
    await page.reload();
    await page.locator("[data-mail-toggle]").first().click();
    await emailRow.locator("td").first().click({ position: { x: 5, y: 5 } });
    assert.equal(await preview.getByLabel("Subject", { exact: true }).inputValue(), "Updated incident template");
    await preview.locator("[data-mail-upload]").setInputFiles(path.join(__dirname, "../assets/mail/section-02-1.oft"));
    await preview.getByText(/Imported section-02-1.oft/).waitFor();
    assert.equal(await preview.getByLabel("Subject", { exact: true }).inputValue(), "[DUMMY TEMPLATE] Report Acknowledgment");
    await preview.getByRole("button", { name: "Save", exact: true }).click();
    await emailRow.press("Enter");
    const importedDownloadEvent = page.waitForEvent("download");
    await page.getByRole("link", { name: "Initial Notification", exact: true }).click();
    const importedDownload = await importedDownloadEvent;
    assert.equal(new MsgReader(await fs.readFile(await importedDownload.path())).getFileData().subject, "[DUMMY TEMPLATE] Report Acknowledgment");
    await emailRow.press("Enter");
    await preview.locator("[data-mail-upload]").setInputFiles({ name: "invalid.oft", mimeType: "application/octet-stream", buffer: Buffer.from("not an Outlook file") });
    await preview.getByText(/Import failed: This is not a binary Outlook/).waitFor();
    assert.equal(await preview.getByLabel("Subject", { exact: true }).inputValue(), "[DUMMY TEMPLATE] Report Acknowledgment");
    await emailRow.locator("td").first().click({ position: { x: 5, y: 5 } });
    assert.equal(await preview.isVisible(), false);
    await emailRow.focus();
    await emailRow.press("Enter");
    assert.equal(await preview.isVisible(), true);
    await emailRow.press("Space");
    assert.equal(await preview.isVisible(), false);
    await page.getByRole("searchbox", { name: "Search portal" }).fill("Patch Reminder");
    await page.waitForFunction(() => document.querySelectorAll(".mail-subsection-row").length === 1);
    assert.equal(await page.locator(".mail-section-row").count(), 1);
    assert.equal(await page.getByRole("link", { name: "Patch Reminder", exact: true }).isVisible(), true);
    await page.getByRole("searchbox", { name: "Search portal" }).fill("no-such-template");
    await page.getByText("No mail templates match.", { exact: true }).waitFor();
    await page.getByRole("searchbox", { name: "Search portal" }).fill("");
    await page.locator(".mail-section-row").first().waitFor();
    assert.equal(await page.getByRole("button", { name: "Edit title", exact: true }).count(), 0);
    await emailRow.locator("td").first().click({ position: { x: 5, y: 5 } });
    await emailRow.getByRole("textbox", { name: "Title", exact: true }).fill("Custom notification");
    await emailRow.getByRole("textbox", { name: "Title", exact: true }).press("Tab");
    await emailRow.getByRole("textbox", { name: "Description", exact: true }).fill("Custom description");
    await emailRow.getByRole("textbox", { name: "Description", exact: true }).press("Tab");
    await preview.getByRole("button", { name: "Save", exact: true }).click();
    assert.equal(await emailRow.locator("a").innerText(), "Custom notification");
    await page.reload();
    await page.locator("[data-mail-toggle]").first().click();
    assert.equal(await emailRow.locator("a").innerText(), "Custom notification");
    assert.equal(await emailRow.locator("td").nth(1).innerText(), "Custom description");
    assert.equal(await page.locator(".mail-table th").last().innerText(), "");
    await emailRow.getByRole("button", { name: "Delete row", exact: true }).click();
    assert.equal(await emailRow.count(), 0);
    await page.reload();
    assert.equal(await emailRow.count(), 0);
    await page.locator("#mail-section-select").selectOption("section-04");
    await page.getByRole("button", { name: "Add Email", exact: true }).click();
    const addDialog = page.getByRole("dialog", { name: "Add Email", exact: true });
    assert.equal(await addDialog.isVisible(), true);
    assert.equal(await page.locator(".mail-subsection-row").count(), 6);
    await addDialog.getByRole("button", { name: "Cancel", exact: true }).click();
    assert.equal(await page.locator(".mail-subsection-row").count(), 6);
    await page.getByRole("button", { name: "Add Email", exact: true }).click();
    assert.equal(await addDialog.getByLabel("Category", { exact: true }).inputValue(), "section-04");
    await addDialog.getByLabel("Title", { exact: true }).fill("New coverage request");
    await addDialog.getByLabel("Description", { exact: true }).fill("Coverage coordination");
    await addDialog.getByLabel("To", { exact: true }).fill("coverage@example.com");
    await addDialog.getByLabel("Subject", { exact: true }).fill("Additional coverage");
    await addDialog.getByLabel("Body", { exact: true }).fill("Please provide additional coverage this week.");
    await addDialog.getByRole("button", { name: "Save", exact: true }).click();
    assert.equal(await addDialog.isVisible(), false);
    assert.equal(await page.locator(".mail-subsection-row").count(), 7);
    const addedRow = page.locator(".mail-subsection-row").first();
    const addedId = await addedRow.getAttribute("data-mail-preview-toggle");
    const addedPreview = page.locator(`#mail-preview-${addedId}`);
    await addedRow.getByRole("textbox", { name: "Title", exact: true }).fill("New coverage request");
    await addedRow.getByRole("textbox", { name: "Title", exact: true }).press("Tab");
    await addedPreview.getByLabel("Subject", { exact: true }).fill("Additional coverage");
    await addedPreview.getByLabel("Body", { exact: true }).fill("Please provide additional coverage this week.");
    await addedPreview.getByRole("button", { name: "Save", exact: true }).click();
    await addedRow.press("Enter");
    const addedDownloadEvent = page.waitForEvent("download");
    await addedRow.getByRole("link", { name: "New coverage request", exact: true }).click();
    const addedDownload = await addedDownloadEvent;
    assert.equal(new MsgReader(await fs.readFile(await addedDownload.path())).getFileData().subject, "Additional coverage");
    const importBytes = await fs.readFile(path.join(__dirname, "../assets/mail/section-02-1.oft"));
    const chooserEvent = page.waitForEvent("filechooser");
    await page.getByRole("button", { name: "Import", exact: true }).click();
    const chooser = await chooserEvent;
    await chooser.setFiles([
      { name: "first.oft", mimeType: "application/octet-stream", buffer: importBytes },
      { name: "second.msg", mimeType: "application/octet-stream", buffer: importBytes },
      { name: "invalid.oft", mimeType: "application/octet-stream", buffer: Buffer.from("invalid") },
    ]);
    await page.locator("[data-mail-import-status]").filter({ hasText: "2 emails added." }).waitFor();
    assert.match(await page.locator("[data-mail-import-status]").innerText(), /invalid.oft/);
    assert.equal(await page.locator(".mail-subsection-row").count(), 9);
    await page.reload();
    await page.locator("#mail-section-select").selectOption("section-04");
    assert.equal(await page.locator(".mail-subsection-row").count(), 9);
    assert.equal(await page.getByRole("link", { name: "New coverage request", exact: true }).count(), 1);
    assert.equal(await page.getByRole("link", { name: "[DUMMY TEMPLATE] Report Acknowledgment", exact: true }).count(), 2);
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.getByRole("button", { name: "Mail", exact: true }).isVisible(), true);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    assert.deepEqual(errors, []);
    console.log("PASS: Mail hierarchy, hover, previews, edits, Save/reload persistence, updated OFT content, upload/save/download, invalid imports, search, and mobile layout.");
  } finally {
    await browser.close();
  }
})().catch((error) => { console.error(error); process.exitCode = 1; });
